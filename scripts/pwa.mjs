/**
 * Web / mobile (PWA) build: `vite build --mode web` (npm run build:web).
 *
 * The desktop build is untouched: this plugin does nothing outside the `web`
 * mode. In that mode it
 *   - links the web app manifest and the phone meta tags into index.html,
 *   - writes `sw.js`, a service worker that precaches every built file so the
 *     installed app starts offline. It answers same-origin GETs only: requests
 *     to the user's own servers (transcription server, GitLab, LLM) are never
 *     touched, cached or proxied.
 *
 * A new version is downloaded in the background and takes over the next time
 * the app is opened (no skipWaiting): an update never reloads a page that may
 * be recording.
 */
import { createHash } from 'node:crypto';
import { readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

export const PWA_MODE = 'web';

/** The web app manifest (paths are relative, so any sub-path hosting works). */
export function webManifest(version) {
  return {
    name: 'Local Transcribe',
    short_name: 'Transcribe',
    description: 'Privacy-first meeting recorder. Your recording and transcript stay on this device.',
    id: './',
    start_url: './',
    scope: './',
    display: 'standalone',
    orientation: 'any',
    background_color: '#ffffff',
    theme_color: '#000000',
    categories: ['productivity', 'utilities'],
    version,
    icons: [
      { src: 'pwa/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: 'pwa/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: 'pwa/maskable-192.png', sizes: '192x192', type: 'image/png', purpose: 'maskable' },
      { src: 'pwa/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  };
}

/** Tags added to <head> in the web build. */
export function headTags() {
  const meta = (name, content) => ({ tag: 'meta', attrs: { name, content }, injectTo: 'head' });
  return [
    { tag: 'link', attrs: { rel: 'manifest', href: './manifest.webmanifest' }, injectTo: 'head' },
    { tag: 'link', attrs: { rel: 'apple-touch-icon', href: './pwa/apple-touch-icon.png' }, injectTo: 'head' },
    meta('theme-color', '#000000'),
    meta('mobile-web-app-capable', 'yes'),
    meta('apple-mobile-web-app-capable', 'yes'),
    meta('apple-mobile-web-app-title', 'Transcribe'),
    meta('apple-mobile-web-app-status-bar-style', 'default'),
  ];
}

/**
 * The service worker. `files` are the app's own URLs (relative to the scope);
 * `version` changes whenever any of them does, so the browser sees a new
 * worker and refreshes the cache.
 */
export function serviceWorkerSource(files, version) {
  return `// Generated by scripts/pwa.mjs — do not edit.
const CACHE = 'local-transcribe-${version}';
const FILES = ${JSON.stringify(files)};
const SCOPE = new URL('./', self.location.href);
const INDEX = new URL('index.html', SCOPE).href;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(FILES.map((f) => new URL(f, SCOPE).href))),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k.startsWith('local-transcribe-') && k !== CACHE).map((k) => caches.delete(k))),
    ).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  // Only the app's own files: everything else goes to the network untouched.
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(caches.match(INDEX).then((hit) => hit || fetch(request)));
    return;
  }
  event.respondWith(caches.match(request, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(request)));
});
`;
}

function publicFiles(dir) {
  try {
    return readdirSync(dir).flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory()
        ? publicFiles(path).map((f) => `${name}/${f}`)
        : [relative(dir, path).split(sep).join('/')];
    });
  } catch {
    return [];
  }
}

/** Vite plugin: active only in the `web` mode. */
export function pwa({ version }) {
  let enabled = false;
  let publicDir = '';
  return {
    name: 'local-transcribe-pwa',
    configResolved(config) {
      enabled = config.mode === PWA_MODE && config.command === 'build';
      publicDir = config.publicDir;
    },
    transformIndexHtml() {
      return enabled ? headTags() : [];
    },
    generateBundle(_options, bundle) {
      if (!enabled) return;
      this.emitFile({
        type: 'asset',
        fileName: 'manifest.webmanifest',
        source: JSON.stringify(webManifest(version), null, 2),
      });
      const built = Object.keys(bundle).filter((f) => !f.endsWith('.map') && f !== 'index.html');
      const files = ['./', 'index.html', 'manifest.webmanifest', ...publicFiles(publicDir), ...built.sort()];
      const unique = [...new Set(files)];
      const hash = createHash('sha256').update(version).update(unique.join('\n'));
      for (const name of built) {
        const item = bundle[name];
        hash.update(item.type === 'chunk' ? item.code : item.source);
      }
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: serviceWorkerSource(unique, hash.digest('hex').slice(0, 12)),
      });
    },
  };
}
